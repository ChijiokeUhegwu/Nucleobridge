/**
 * generate-second-tokens.js
 * 
 * Node.js utility script to parse exported design tokens (tokens-complete.json)
 * and generate second-tokens.css.
 * 
 * Strict Boundary Requirement:
 * - Primitive colors (e.g. Neutral 90, Primary 40) are resolved in-memory during build.
 * - Under NO circumstances are primitive colors exposed or outputted as CSS custom properties.
 * - ONLY semantic color roles (e.g. --color-surface, --color-primary, --color-on-primary)
 *   are outputted for interface usage.
 * 
 * Output Target: task-01-design-system/main-tokens.css
 */

const fs = require('fs');
const path = require('path');

const INPUT_PATH = path.resolve(__dirname, '../evidence/tokens-complete.json');
const OUTPUT_PATH = path.resolve(__dirname, '../main-tokens.css');

/**
 * Formats 8-character hex (#rrggbbaa) to 6-character hex (#rrggbb) if alpha is 255 (ff),
 * or rgba(...) if alpha has transparency.
 */
function formatColor(hex) {
  if (typeof hex !== 'string') return hex;
  const cleaned = hex.trim();

  if (/^#[0-9a-fA-F]{8}$/.test(cleaned)) {
    const r = parseInt(cleaned.slice(1, 3), 16);
    const g = parseInt(cleaned.slice(3, 5), 16);
    const b = parseInt(cleaned.slice(5, 7), 16);
    const a = parseInt(cleaned.slice(7, 9), 16);

    if (a === 255) {
      return `#${cleaned.slice(1, 7).toLowerCase()}`;
    }
    const alpha = Number((a / 255).toFixed(2));
    return `rgba(${r}, ${g}, ${b}, ${alpha})`;
  }

  return cleaned.toLowerCase();
}

/**
 * Normalizes string to kebab-case slug
 */
function slugify(str) {
  return str
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9_-]/g, '');
}

/**
 * Resolves a token reference like "{primitives.color palettes.primary.primary80}"
 * directly against the tokens JSON to obtain the raw color value.
 */
function resolveValue(refString, rootData) {
  if (typeof refString !== 'string') return refString;
  if (!refString.startsWith('{') || !refString.endsWith('}')) {
    return refString;
  }

  const pathSegments = refString.slice(1, -1).split('.');
  let current = rootData;

  for (const segment of pathSegments) {
    if (current && typeof current === 'object' && segment in current) {
      current = current[segment];
    } else {
      console.warn(`[WARN] Could not resolve token reference: ${refString} at segment: ${segment}`);
      return null;
    }
  }

  if (current && typeof current === 'object' && 'value' in current) {
    // If the referenced value is itself a reference, recursively resolve it
    return resolveValue(current.value, rootData);
  }

  return current;
}

function buildMainTokens(tokensData) {
  const lines = [];

  lines.push('/**',
    ' * ============================================================================',
    ' * NUCLEOBRIDGE DESIGN TOKENS (second-tokens.css)',
    ' * Source of Truth: task-01-design-system/evidence/06-tokens-complete.json',
    ' * Generated by: task-01-design-system/scripts/generate-second-tokens.js',
    ' * ============================================================================',
    ' *',
    ' * STRICT INTERFACE ARCHITECTURE:',
    ' *',
    ' * 1. ZERO PRIMITIVE EXPOSURE:',
    ' *    - Underlying primitive palette colors (e.g. neutral-90, primary-40) are',
    ' *      deliberately withheld and NOT exported as usable CSS variables.',
    ' *    - This hard boundary prevents components from bypassing design semantics.',
    ' *',
    ' * 2. SEMANTIC COLOR ROLES ONLY:',
    ' *    - All color variables (--color-*) represent contextual, semantic UI roles.',
    ' *    - Components must strictly and exclusively consume these semantic roles.',
    ' *',
    ' * 3. TYPOGRAPHY & ELEVATION:',
    ' *    - DM Sans scale tokens with 1.5 line-height multiplier.',
    ' *    - Elevated drop shadows tinted with primary brand tone (#0F6E56).',
    ' * ============================================================================',
    ' */',
    '',
    ':root {'
  );

  let roleCount = 0;
  let typographyCount = 0;
  let effectCount = 0;

  // 1. Semantic Color Roles (Mapped from primitives, primitives completely hidden)
  if (tokensData['color roles']) {
    lines.push('  /* --------------------------------------------------------------------------',
      '   * 1. SEMANTIC COLOR ROLES (THE ONLY ACCESSIBLE UI COLORS)',
      '   * Primitive colors are resolved in-memory and NOT exposed as CSS variables.',
      '   * -------------------------------------------------------------------------- */'
    );

    const roles = tokensData['color roles'];
    for (const [roleName, token] of Object.entries(roles)) {
      const rawResolved = resolveValue(token.value, tokensData);
      const formattedColor = formatColor(rawResolved);
      const roleSlug = slugify(roleName);

      lines.push(`  --color-${roleSlug}: ${formattedColor};`);
      roleCount++;

      // Provide normalized alias if the export contained a known typo (e.g. "on terrtiary fixed")
      if (roleName === 'on terrtiary fixed') {
        lines.push(`  --color-on-tertiary-fixed: ${formattedColor}; /* normalized alias */`);
      }
    }
    lines.push('');
  }

  // 2. Elevation / Shadow Tokens
  if (tokensData.effect) {
    lines.push('  /* --------------------------------------------------------------------------',
      '   * 2. ELEVATION / SHADOW TOKENS',
      '   * Tinted with primary brand color (#0F6E56) for cohesive visual depth.',
      '   * -------------------------------------------------------------------------- */'
    );

    const effects = tokensData.effect;
    for (const [effectName, token] of Object.entries(effects)) {
      const val = token.value;
      const shadowColor = formatColor(val.color);
      const cleanName = slugify(effectName.replace(/\s*shadow$/i, ''));
      const shadowCss = `${val.offsetX}px ${val.offsetY}px ${val.radius}px ${val.spread}px ${shadowColor}`;
      lines.push(`  --shadow-${cleanName}: ${shadowCss};`);
      effectCount++;
    }
    lines.push('');
  }

  // 3. Typography Tokens
  if (tokensData.typography) {
    lines.push('  /* --------------------------------------------------------------------------',
      '   * 3. TYPOGRAPHY DESIGN TOKENS',
      '   * Font: DM Sans, consistent 1.5 line-height multiplier.',
      '   * -------------------------------------------------------------------------- */',
      "  --font-family-base: 'DM Sans', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;"
    );

    const typos = tokensData.typography;
    for (const [styleName, token] of Object.entries(typos)) {
      const styleSlug = slugify(styleName);
      const fontSize = token.fontSize.value;
      const lineHeight = token.lineHeight.value;
      const letterSpacing = token.letterSpacing.value;
      const fontWeight = token.fontWeight.value;

      lines.push(`  --typography-${styleSlug}-font-size: ${fontSize}px;`);
      lines.push(`  --typography-${styleSlug}-line-height: ${lineHeight}px;`);
      lines.push(`  --typography-${styleSlug}-letter-spacing: ${letterSpacing}px;`);
      lines.push(`  --typography-${styleSlug}-font-weight: ${fontWeight};`);
      typographyCount++;
    }
  }

  lines.push('}', '');

  // 4. Typography Utility Classes
  if (tokensData.typography) {
    lines.push('/* ----------------------------------------------------------------------------',
      ' * 4. TYPOGRAPHY UTILITY CLASSES',
      ' * Semantic utility classes matching the 15 type scale roles.',
      ' * ---------------------------------------------------------------------------- */'
    );

    const typos = tokensData.typography;
    for (const [styleName] of Object.entries(typos)) {
      const styleSlug = slugify(styleName);
      lines.push(
        `.text-${styleSlug} {`,
        `  font-family: var(--font-family-base);`,
        `  font-size: var(--typography-${styleSlug}-font-size);`,
        `  line-height: var(--typography-${styleSlug}-line-height);`,
        `  letter-spacing: var(--typography-${styleSlug}-letter-spacing);`,
        `  font-weight: var(--typography-${styleSlug}-font-weight);`,
        `}`,
        ''
      );
    }
  }

  return {
    css: lines.join('\n'),
    stats: { roleCount, typographyCount, effectCount }
  };
}

function main() {
  console.log('Building main-tokens.css...');
  console.log(`Source: ${INPUT_PATH}`);
  console.log(`Target: ${OUTPUT_PATH}`);

  if (!fs.existsSync(INPUT_PATH)) {
    console.error(`[ERROR] File not found: ${INPUT_PATH}`);
    process.exit(1);
  }

  const rawData = fs.readFileSync(INPUT_PATH, 'utf8');
  const tokensData = JSON.parse(rawData);

  const { css, stats } = buildMainTokens(tokensData);

  fs.writeFileSync(OUTPUT_PATH, css, 'utf8');

  console.log('Successfully generated main-tokens.css!');
  console.log(`- Semantic Color Roles: ${stats.roleCount} (Exclusively exposed for UI)`);
  console.log(`- Primitive Colors:     0 exposed (Strict boundary enforced)`);
  console.log(`- Typography Tokens:    ${stats.typographyCount}`);
  console.log(`- Elevation Shadows:    ${stats.effectCount}`);
}

if (require.main === module) {
  main();
}

module.exports = { buildMainTokens };
